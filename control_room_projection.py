def documents_register():
    """Catalog authoritative documents with type, version, and last update."""
    baseline, _ = _baseline()
    governing = baseline.get("governing_documents") or {}
    superseded = set(_as_list(baseline.get("superseded_documents")))
    rows = []

    # 1. The version-bearing governing documents named in the baseline.
    for key, entry in (governing.items() if isinstance(governing, dict) else []):
        if not isinstance(entry, dict) or not entry.get("path"):
            continue
        rel = entry["path"].rstrip("/")
        exists = os.path.exists(os.path.join(ROOT, *rel.split("/")))
        rows.append(
            {
                "title": key.replace("_", " ").title(),
                "type": "Governing document",
                "authority": "Superseded" if rel in superseded else "Canonical",
                "version": entry.get("version"),
                "path": rel,
                "link": _source_link(rel),
                "updated": baseline.get("updated_at"),
                "status": OK if exists else UNAVAILABLE,
            }
        )

    # 2. Named supporting/canonical Markdown records (parse their own date).
    for rel, title, authority in _REGISTER_DOCS:
        abs_path = os.path.join(ROOT, *rel.split("/"))
        text = _read(abs_path)
        rows.append(
            {
                "title": title,
                "type": "Governance record",
                "authority": authority,
                "version": None,
                "path": rel,
                "link": _source_link(rel),
                "updated": _declared_date(text) or _mtime_iso(abs_path),
                "status": OK if text is not None else UNAVAILABLE,
            }
        )

    # 3. Explicitly retired documents, so history is visible, not hidden.
    for rel in sorted(superseded):
        rel = rel.rstrip("/")
        display = rel.split("/")[-1]
        rows.append(
            {
                "title": display,
                "type": "Document",
                "authority": "Superseded",
                "version": None,
                "path": rel if "/" in rel else None,
                "link": _source_link(rel) if "/" in rel else None,
                "updated": None,
                "status": OK,
            }
        )

    return {"status": OK if rows else UNKNOWN, "records": rows,
            "source": _source("docs/governance/CURRENT_BASELINE.yaml", status=OK)}


def decisions():
    """Parse the append-only manager decision log into dated records."""
    path = os.path.join(GOV, "DECISIONS.md")
    text = _read(path)
    rel = _rel(path)
    if text is None:
        return {"status": UNAVAILABLE, "records": [], "source": _source(
            rel, status=UNAVAILABLE)}

    records = []
    current = None
    for line in text.splitlines():
        heading = re.match(r"^##\s+(.*)$", line)
        if heading:
            if current:
                records.append(current)
            title = heading.group(1).strip()
            date_match = _ISO_DATE.search(title)
            current = {
                "date": date_match.group(1) if date_match else None,
                "title": re.sub(r"^20\d{2}-\d{2}-\d{2}\s*[-—:]\s*", "", title),
                "points": [],
            }
        elif current is not None:
            bullet = re.match(r"^[-*]\s+(.*)$", line.strip())
            if bullet:
                current["points"].append(bullet.group(1).strip())
    if current:
        records.append(current)

    # Newest first when dates are present.
    records.sort(key=lambda record: record["date"] or "", reverse=True)
    return {"status": OK if records else UNKNOWN, "records": records,
            "source": _source(rel, updated=_declared_date(text), status=OK)}


def delivery_health():
    """Deployment/pipeline facts the repository records, plus a truthful note
    that no *live* Azure DevOps integration is configured for this dashboard.

    The brief forbids adding broad delivery-platform credentials merely to
    populate the dashboard, and this build handles no tokens. So Delivery Health
    shows what the authoritative baseline records and clearly marks the live
    integration as unavailable rather than manufacturing green status.
    """
    summary = governance_summary()
    if summary["status"] == UNAVAILABLE:
        return {"status": UNAVAILABLE, "source": summary["source"],
                "live_integration": UNAVAILABLE, "records": []}

    authority = summary["authority"]
    records = [
        {
            "label": "Last recorded application-behaviour release",
            "value": authority.get("application_behavior_commit"),
            "detail": (
                "pipeline "
                f"{authority.get('application_behavior_pipeline')}"
                if authority.get("application_behavior_pipeline")
                else None
            ),
            "status": OK if authority.get("application_behavior_commit")
            else UNKNOWN,
        },
        {
            "label": "Production URL",
            "value": authority.get("production_url"),
            "detail": "Recorded in baseline; not probed live by this dashboard.",
            "status": OK if authority.get("production_url") else UNKNOWN,
        },
    ]
    return {
        "status": OK,
        "source": summary["source"],
        # No live Azure DevOps Boards/Pipelines integration is configured; this
        # dashboard reads no delivery credentials.
        "live_integration": UNAVAILABLE,
        "live_integration_note": (
            "Live Azure DevOps Pipelines/Boards integration is not configured. "
            "Figures below are the repository's recorded release facts, not a "
            "live probe."
        ),
        "records": records,
    }


def recent_changes(limit=15):
    """A source-backed change timeline.

    Three tiers, most-current first:
      1. Live local git (development) — always the freshest when present.
      2. The build-time snapshot (production) — captured by the Azure
         pipeline before ``.git`` is stripped from the deployment artifact.
      3. Truthful ``unavailable`` if neither source exists.

    Never invents activity: a tier that cannot be read is skipped, not padded.
    """
    try:
        result = subprocess.run(
            [
                "git",
                "log",
                f"-{int(limit)}",
                "--date=short",
                "--pretty=format:%h\x1f%ad\x1f%an\x1f%s",
            ],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        result = None

    if result and result.returncode == 0 and result.stdout.strip():
        items = []
        for line in result.stdout.splitlines():
            parts = line.split("\x1f")
            if len(parts) != 4:
                continue
            commit, date, author, subject = parts
            items.append(
                {
                    "commit": commit,
                    "date": date,
                    "author": author,
                    "subject": subject,
                }
            )
        return {
            "status": OK if items else UNKNOWN,
            "records": items,
            "tier": "live_git",
            "source": _source(".git", status=OK),
        }

    snapshot = _read_snapshot()
    if snapshot and isinstance(snapshot.get("commits"), list):
        items = [
            {
                "commit": commit.get("commit"),
                "date": commit.get("date"),
                "author": commit.get("author"),
                "subject": commit.get("subject"),
            }
            for commit in snapshot["commits"]
            if isinstance(commit, dict)
        ][:limit]
        return {
            "status": OK if items else UNKNOWN,
            "records": items,
            "tier": "build_snapshot",
            "source": {
                # Never committed (see .gitignore) — no Azure repo link exists
                # for this generated file, so it deliberately carries none.
                "path": "control_room_snapshot.json (generated at build time)",
                "link": None,
                "updated": _format_snapshot_timestamp(
                    snapshot.get("generated_at")
                ),
                "status": OK,
            },
        }

    return {
        "status": UNAVAILABLE,
        "note": (
            "Git history is not available in this environment, and no "
            "build-time snapshot (control_room_snapshot.json) was found. "
            "Production deployment artifacts exclude .git; the Azure "
            "pipeline generates the snapshot before packaging — see "
            "docs/control-room/V2_LIVE_SYNC_SPEC.md."
        ),
        "records": [],
        "tier": None,
        "source": _source(".git", status=UNAVAILABLE),
    }


def build_identity():
    """What commit is actually running right now.

    Production: identifies the deployed artifact's commit and pipeline build
    id from the Tier 0 snapshot. Local development: reports the local git
    HEAD instead, explicitly labelled as local rather than a packaged build —
    the two are never conflated. Feeds the Overview "Production" status card
    and the deployment-drift comparison in ``repository_activity``.
    """
    snapshot = _read_snapshot()
    if snapshot:
        build = snapshot.get("build") or {}
        commits = snapshot.get("commits") or []
        head = commits[0] if commits and isinstance(commits[0], dict) else {}
        full_sha = build.get("source_version")
        return {
            "status": OK,
            "environment": "production_build",
            "commit": (full_sha[:7] if full_sha else head.get("commit")),
            "commit_full": full_sha,
            "subject": head.get("subject"),
            "build_id": build.get("id"),
            "source_branch": build.get("source_branch"),
            "generated_at": _format_snapshot_timestamp(
                snapshot.get("generated_at")
            ),
        }

    local_head = _local_git_head()
    if local_head:
        return {
            "status": OK,
            "environment": "local_development",
            "commit": local_head["commit"],
            "commit_full": local_head["commit_full"],
            "subject": local_head["subject"],
            "build_id": None,
            "source_branch": None,
            "generated_at": None,
        }

    return {
        "status": UNAVAILABLE,
        "environment": "unknown",
        "commit": None,
        "commit_full": None,
        "subject": None,
        "build_id": None,
        "source_branch": None,
        "generated_at": None,
    }


def traceability():
    """Partial-by-design traceability signals derived from available sources.

    We only claim what the files support. Anything the current records cannot
    establish is surfaced as an explicit gap, never silently resolved.
    """
    inits = initiatives()
    gov = governance_summary()
    signals = []

    if gov["status"] == OK:
        active = gov["active_packages"]
        for package in active:
            signals.append(
                {
                    "kind": "Active package traced",
                    "subject": package.get("id"),
                    "detail": (
                        f"Owner {package.get('owner') or 'unknown'} · lane "
                        f"{package.get('lane') or 'unknown'}"
                    ),
                    "status": OK if package.get("path") else PARTIAL,
                }
            )

    if inits["status"] == OK:
        for record in inits["records"]:
            if record["status"] == "Completed" and not record[
                "has_completion_report"
            ]:
                signals.append(
                    {
                        "kind": "Gap: completed without a closeout report",
                        "subject": record["id"],
                        "detail": "Marked complete in baseline; no "
                        "COMPLETION_REPORT.md found.",
                        "status": PARTIAL,
                    }
                )
            if not record["has_readme"]:
                signals.append(
                    {
                        "kind": "Gap: package without a README",
                        "subject": record["id"],
                        "detail": "Initiative directory has no README.md.",
                        "status": PARTIAL,
                    }
                )

    return {
        "status": OK if signals else UNKNOWN,
        "partial": True,
        "note": (
            "Traceability is partial: the current records link initiatives, "
            "owners, and closeout evidence, but do not yet encode a full "
            "requirement → test → deployment chain."
        ),
        "records": signals,
    }


def _current_app_config():
    """The active Flask app's config, or ``{}`` outside a request/app context.

    Imported lazily so this module has no hard Flask dependency and stays
    callable (e.g. from tests or a script) without a running application —
    in that case Tier 1 config reads as empty, which correctly resolves to
    ``not_configured`` rather than raising.
    """
    try:
        from flask import current_app, has_app_context

        if has_app_context():
            return current_app.config
    except RuntimeError:
        pass
    return {}


def _compute_drift(build, activity):
    """Compare the deployed build's commit (Tier 0) against the live `main`
    tip (Tier 1). Never guesses: missing data on either side, or a deployed
    commit that isn't found in the fetched history, is reported ``unknown`` —
    never silently treated as up to date or as a known distance behind.
    """
    deployed_full = (build or {}).get("commit_full")
    main_tip_full = None
    if activity and activity.get("status") in (OK, STALE):
        for branch in activity.get("branches", {}).get("items", []):
            if branch.get("name") == "main":
                main_tip_full = branch.get("commit_full")
                break

    if not deployed_full or not main_tip_full:
        return {"state": "unknown", "detail": None, "pending_commits": []}

    if deployed_full == main_tip_full:
        return {"state": "up_to_date", "detail": None, "pending_commits": []}

    commits = activity.get("commits_main", {}).get("items", [])
    shas = [commit.get("commit_full") for commit in commits]
    if deployed_full not in shas:
        return {"state": "unknown", "detail": None, "pending_commits": []}

    pending = commits[: shas.index(deployed_full)]
    return {
        "state": "behind",
        "detail": f"{len(pending)} commit(s) ahead of the deployed build",
        "pending_commits": pending,
    }


def repository_activity(app_config=None, build=None):
    """Tier 1: live Azure DevOps activity, plus the Tier0×Tier1 drift check.

    ``app_config`` lets callers inject the Flask config explicitly (as
    ``control_room_routes`` does); it defaults to the active app's config
    when available and to ``{}`` otherwise, which correctly reads as
    "not configured" rather than raising outside a request context.
    """
    from services.azure_devops_read import fetch_repository_activity

    if app_config is None:
        app_config = _current_app_config()
    if build is None:
        build = build_identity()

    activity = fetch_repository_activity(app_config)
    return {**activity, "drift": _compute_drift(build, activity)}


def overview(sections):
    """A calm roll-up computed from the already-built sections."""
    gov = sections["governance"]
    inits = sections["initiatives"]
    active_count = len(gov.get("active_packages", [])) if gov[
        "status"] == OK else None
    completed_count = len(gov.get("completed_packages", [])) if gov[
        "status"] == OK else None
    holds = gov.get("holds", []) if gov["status"] == OK else []

    warnings = []
    trace = sections["traceability"]
    if trace["status"] == OK:
        warnings.extend(
            item for item in trace["records"] if item["status"] != OK
        )
    if sections["recent_changes"]["status"] == UNAVAILABLE:
        warnings.append(
            {
                "kind": "Source unavailable",
                "subject": "Recent changes",
                "detail": sections["recent_changes"].get("note"),
                "status": UNAVAILABLE,
            }
        )
    if sections["delivery"].get("live_integration") == UNAVAILABLE:
        warnings.append(
            {
                "kind": "Integration not configured",
                "subject": "Delivery health",
                "detail": sections["delivery"].get("live_integration_note"),
                "status": UNAVAILABLE,
            }
        )
    repo_activity = sections.get("repository_activity") or {}
    if repo_activity.get("status") == "not_configured":
        warnings.append(
            {
                "kind": "Live sync not configured",
                "subject": "Repository activity",
                "detail": repo_activity.get("note"),
                "status": UNAVAILABLE,
            }
        )
    elif repo_activity.get("status") in (UNAVAILABLE, STALE):
        warnings.append(
            {
                "kind": "Live sync "
                + ("unavailable" if repo_activity["status"] == UNAVAILABLE
                   else "stale"),
                "subject": "Repository activity",
                "detail": repo_activity.get("note"),
                "status": repo_activity["status"],
            }
        )
    drift = repo_activity.get("drift") or {}
    if drift.get("state") == "behind":
        warnings.append(
            {
                "kind": "Deployment drift",
                "subject": "Production",
                "detail": drift.get("detail"),
                "status": PARTIAL,
            }
        )

    return {
        "active_count": active_count,
        "completed_count": completed_count,
        "initiative_count": len(inits.get("records", [])),
        "holds": holds,
        "manager": gov.get("manager", {}).get("label") if gov[
            "status"] == OK else None,
        "production_url": gov.get("authority", {}).get("production_url") if gov[
            "status"] == OK else None,
        "bible": gov.get("bible") if gov["status"] == OK else None,
        "roadmap": gov.get("roadmap") if gov["status"] == OK else None,
        "warnings": warnings,
        "next_gate": gov.get("next_gate") if gov["status"] == OK else None,
    }


def build_projection(app_config=None):
    """Assemble the full, JSON-serialisable read-only projection.

    ``app_config`` is the Flask app's config mapping (for Tier 1's Azure
    DevOps settings); callers inside a request may omit it and it is read
    from the active app automatically. Omitting it outside any app context
    (e.g. a script or a test) correctly yields Tier 1 = "not configured"
    rather than raising.
    """
    generated_at = datetime.now(tz=timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    build = build_identity()
    sections = {
        "governance": governance_summary(),
        "initiatives": initiatives(),
        "documents": documents_register(),
        "decisions": decisions(),
        "delivery": delivery_health(),
        "recent_changes": recent_changes(),
        "traceability": traceability(),
        "build_identity": build,
        "repository_activity": repository_activity(app_config, build=build),
    }
    sections["overview"] = overview(sections)
    sections["generated_at"] = generated_at
    sections["read_only"] = True
    return sections
