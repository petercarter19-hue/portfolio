"""Read-only projection of PeerSlate project truth for the owner Control Room.

The Control Room is an owner-only, read-only *projection* of authoritative
project sources. This module derives everything it shows from version-controlled
repository files (governance records, initiative packages, the decision log) plus
optional local Git metadata. It:

* performs no writes and calls no mutation of any kind;
* uses no runtime AI generation (deterministic, source-backed rendering only);
* reads only from fixed, code-owned repository roots — no request input is ever
  turned into a filesystem path, so directory traversal is structurally
  impossible;
* never touches secrets, tokens, connection strings, or the database;
* returns, for every fact, a source path, a best-known timestamp, and a status
  so the UI can distinguish ``ok`` / ``unknown`` / ``unavailable`` / ``partial``.

If a source is missing or malformed, the relevant provider degrades to a truthful
``unavailable`` / ``unknown`` state rather than raising or manufacturing a
favourable status.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(ROOT, "docs")
GOV = os.path.join(DOCS, "governance")
INITIATIVES_DIR = os.path.join(DOCS, "initiatives")

# Build-time snapshot (Tier 0): generated by
# scripts/generate_control_room_snapshot.py in the Azure pipeline, before the
# CopyFiles step packages the deployment artifact (which excludes .git). Not
# tracked in git (see .gitignore) — absent in a fresh checkout, present in a
# deployed production artifact and safe to regenerate locally for testing.
SNAPSHOT_PATH = os.path.join(ROOT, "control_room_snapshot.json")
SNAPSHOT_SCHEMA_VERSION = 1

# Status vocabulary shared with the template so colour is never the only signal.
OK = "ok"
UNKNOWN = "unknown"
UNAVAILABLE = "unavailable"
PARTIAL = "partial"
STALE = "stale"

# Repository-relative web base for "open source" links. Azure DevOps is the
# authoritative remote; links are informational and open the file on the host.
AZURE_REPO_WEB = (
    "https://dev.azure.com/peerslate19/portfolio-site/_git/portfolio-site"
    "?path=/{path}"
)

_ISO_DATE = re.compile(r"(20\d{2}-\d{2}-\d{2})")
_DECLARED_DATE = re.compile(
    r"(?:Updated|Verified|Last updated|Updated by|as of)\D{0,12}(20\d{2}-\d{2}-\d{2})",
    re.IGNORECASE,
)


# ---------------------------------------------------------------------------
# Low-level, dependency-free helpers
# ---------------------------------------------------------------------------

def _read(path):
    """Return file text, or ``None`` if it cannot be read. Never raises."""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            return handle.read()
    except (OSError, ValueError):
        return None


def _rel(path):
    """Repository-relative POSIX path for display and source links."""
    try:
        return os.path.relpath(path, ROOT).replace(os.sep, "/")
    except ValueError:
        return path.replace(os.sep, "/")


def _source_link(rel_path):
    return AZURE_REPO_WEB.format(path=rel_path)


def _mtime_iso(path):
    try:
        return datetime.fromtimestamp(
            os.path.getmtime(path), tz=timezone.utc
        ).strftime("%Y-%m-%d")
    except (OSError, ValueError):
        return None


def _declared_date(text):
    """Best human-declared date from a document's own body, or ``None``.

    Prefers an explicit "Updated/Verified <date>" phrase; falls back to the
    first ISO date near the top of the file. This is more truthful than a file
    mtime, which the Azure build step resets when it repackages the artifact.
    """
    if not text:
        return None
    head = text[:1200]
    match = _DECLARED_DATE.search(head)
    if match:
        return match.group(1)
    match = _ISO_DATE.search(head)
    return match.group(1) if match else None


def _first_heading(text, default=None):
    if not text:
        return default
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("#"):
            return line.lstrip("#").strip()
    return default


def _source(rel_path, updated=None, status=OK):
    """A uniform source-reference record for the UI."""
    return {
        "path": rel_path,
        "link": _source_link(rel_path),
        "updated": updated,
        "status": status,
    }


def _format_snapshot_timestamp(value):
    """Render the snapshot's ISO-8601 UTC timestamp like ``generated_at``
    elsewhere on the page, so every "as of" time reads the same way."""
    if not isinstance(value, str):
        return None
    try:
        parsed = datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ")
    except ValueError:
        return value
    return parsed.strftime("%Y-%m-%d %H:%M UTC")


def _read_snapshot():
    """Parsed ``control_room_snapshot.json``, or ``None`` if missing/invalid.

    Never raises. Unknown/extra fields are ignored for forward compatibility;
    a missing or non-integer ``schema_version`` is treated as absent rather
    than guessed at.
    """
    text = _read(SNAPSHOT_PATH)
    if text is None:
        return None
    try:
        data = json.loads(text)
    except (ValueError, TypeError):
        return None
    if not isinstance(data, dict) or not isinstance(
        data.get("schema_version"), int
    ):
        return None
    return data


def _local_git_head():
    """The local git HEAD (short + full SHA, subject), or ``None``.

    Used only as the *local development* fallback for ``build_identity`` —
    never presented as a deployed build.
    """
    try:
        head = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=ROOT, capture_output=True, text=True, timeout=5,
        )
        subject = subprocess.run(
            ["git", "log", "-1", "--pretty=format:%s"],
            cwd=ROOT, capture_output=True, text=True, timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        return None

    if head.returncode != 0 or not head.stdout.strip():
        return None

    full_sha = head.stdout.strip()
    return {
        "commit": full_sha[:7],
        "commit_full": full_sha,
        "subject": subject.stdout.strip() if subject.returncode == 0 else None,
    }


# ---------------------------------------------------------------------------
# Minimal YAML-subset reader
# ---------------------------------------------------------------------------
# The governance baseline uses a small, stable YAML subset: mappings, nested
# mappings, block lists of scalars, and block lists of mappings. PyYAML is not a
# project dependency and adding one is out of scope, so this pragmatic reader
# covers exactly that subset. It never raises; on any surprise it returns what
# it parsed so far and the caller degrades gracefully.

def _indent_of(line):
    return len(line) - len(line.lstrip(" "))


def _unquote(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
        return value[1:-1]
    return value


def _split_key_value(text):
    """Split ``key: value`` on the first colon that separates a key from a
    value (a colon followed by end-of-string or whitespace). Returns
    ``(key, value_or_None)`` or ``None`` when the line is not a mapping entry.
    """
    match = re.match(r"^([^:#]+?):(?:\s+(.*))?$", text)
    if not match:
        return None
    key = match.group(1).strip()
    value = match.group(2)
    return key, (value.strip() if value is not None else None)


def _parse_yaml_block(lines, index, indent):
    """Parse a block at the given indent. Returns ``(value, next_index)``."""
    container = None
    while index < len(lines):
        raw = lines[index]
        current_indent = _indent_of(raw)
        if current_indent < indent:
            break
        stripped = raw.strip()
        if current_indent > indent:
            # Defensive: unexpected deeper line with no opener — skip it.
            index += 1
            continue

        if stripped.startswith("- "):
            if not isinstance(container, list):
                container = []
            item_text = stripped[2:].strip()
            element_indent = indent + 2
            key_value = _split_key_value(item_text)
            if key_value and key_value[1] is not None:
                # "- key: value" begins a mapping element; absorb sibling keys.
                element = {key_value[0]: _unquote(key_value[1])}
                index += 1
                nested, index = _parse_yaml_block(lines, index, element_indent)
                if isinstance(nested, dict):
                    element.update(nested)
                container.append(element)
            elif key_value:
                # "- key:" opens a nested block for this element.
                index += 1
                nested, index = _parse_yaml_block(lines, index, element_indent)
                container.append({key_value[0]: nested})
            else:
                container.append(_unquote(item_text))
                index += 1
            continue

        key_value = _split_key_value(stripped)
        if key_value is None:
            index += 1
            continue
        key, value = key_value
        if value is not None and value != "":
            if not isinstance(container, dict):
                container = {}
            container[key] = _unquote(value)
            index += 1
        else:
            # "key:" opens a nested block (mapping or list) one level deeper.
            index += 1
            child, index = _parse_yaml_block(lines, index, indent + 2)
            if not isinstance(container, dict):
                container = {}
            container[key] = child
    return (container if container is not None else {}), index


def parse_yaml_subset(text):
    """Parse the governance YAML subset into nested dict/list structures."""
    if not text:
        return {}
    lines = [
        line.rstrip("\n")
        for line in text.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    try:
        value, _ = _parse_yaml_block(lines, 0, 0)
        return value if isinstance(value, dict) else {}
    except Exception:  # pragma: no cover - reader must never break the page
        return {}


