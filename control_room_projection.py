def _baseline():
    """Parsed CURRENT_BASELINE.yaml plus its source record (or unavailable)."""
    path = os.path.join(GOV, "CURRENT_BASELINE.yaml")
    text = _read(path)
    rel = _rel(path)
    if text is None:
        return {}, _source(rel, status=UNAVAILABLE)
    data = parse_yaml_subset(text)
    status = OK if data else PARTIAL
    return data, _source(rel, updated=data.get("updated_at"), status=status)


def _as_list(value):
    if isinstance(value, list):
        return value
    if value in (None, "", {}):
        return []
    return [value]


def _manager_label(manager):
    """Human label for both legacy and portable manager baseline schemas."""
    legacy_tool = manager.get("tool")
    if legacy_tool:
        return legacy_tool

    role = manager.get("role")
    if role == "package_designated_session_manager":
        return "Package-designated session manager"
    if isinstance(role, str) and role.strip():
        return role.replace("_", " ").strip().capitalize()
    return None


